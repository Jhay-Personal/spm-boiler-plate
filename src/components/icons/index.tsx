export type IconName = keyof typeof paths;

export const ICON_NAMES = Object.keys(paths) as IconName[];

type IconProps = {
  name: IconName;
  /** Rendered square size in px. */
  size?: number;
  className?: string;
};

export function Icon({ name, size = 18, className }: IconProps) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      // Decorative by default: every call site pairs the icon with a text
      // label, or puts an aria-label on the control itself.
      aria-hidden="true"
      focusable="false"
    >
      {paths[name]}
    </svg>
  );
}
